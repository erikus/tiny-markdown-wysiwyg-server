// Bundles web/src into ../internal/web/static and writes THIRD_PARTY_LICENSES.txt
// from the esbuild metafile (the approach used by Simon Willison's web-edit).
import * as esbuild from "esbuild";
import { existsSync, readFileSync, unlinkSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const WEB_DIR = dirname(fileURLToPath(import.meta.url));
const OUT_DIR = resolve(WEB_DIR, "..", "internal", "web", "static");
const JS_ENTRY = join(WEB_DIR, "src", "main.ts");
const CSS_ENTRY = join(WEB_DIR, "src", "app.css");
const JS_OUT = join(OUT_DIR, "app.js");
const CSS_OUT = join(OUT_DIR, "app.css");
const LICENSES_OUT = join(OUT_DIR, "THIRD_PARTY_LICENSES.txt");
// esbuild writes extracted @license comments here; they are folded into
// LICENSES_OUT so the static dir carries a single third-party notice file.
const LEGAL_COMMENTS_OUT = `${JS_OUT}.LEGAL.txt`;
const NODE_MODULES = join(WEB_DIR, "node_modules");
const TARGET = "es2022";
const LICENSE_FILENAMES = ["LICENSE", "LICENSE.md", "LICENSE.txt", "LICENCE", "LICENCE.md", "license", "license.md", "COPYING"];
const SEPARATOR = "-".repeat(72);

/** @type {esbuild.BuildOptions} */
const common = {
  bundle: true,
  minify: true,
  target: TARGET,
  legalComments: "external",
  metafile: true,
  logLevel: "info",
};

const jsResult = await esbuild.build({
  ...common,
  entryPoints: [JS_ENTRY],
  outfile: JS_OUT,
  format: "esm",
  platform: "browser",
});

const cssResult = await esbuild.build({
  ...common,
  entryPoints: [CSS_ENTRY],
  outfile: CSS_OUT,
});

/**
 * Map an esbuild metafile input path (relative to web/) to the nearest
 * package directory under node_modules, or null for first-party sources.
 * @param {string} input
 * @returns {string | null}
 */
function packageDirOf(input) {
  const marker = "node_modules/";
  const idx = input.lastIndexOf(marker);
  if (idx === -1) return null;
  const rest = input.slice(idx + marker.length);
  const segments = rest.split("/");
  const nameSegments = segments[0]?.startsWith("@") ? 2 : 1;
  const pkgRel = segments.slice(0, nameSegments).join("/");
  // Walk up from the file in case of nested node_modules.
  const absPrefix = resolve(WEB_DIR, input.slice(0, idx + marker.length));
  return join(absPrefix, pkgRel);
}

/** @type {Map<string, {name: string, version: string, license: string, text: string}>} */
const packages = new Map();
for (const result of [jsResult, cssResult]) {
  for (const input of Object.keys(result.metafile.inputs)) {
    const dir = packageDirOf(input);
    if (dir === null || packages.has(dir)) continue;
    const pkgJsonPath = join(dir, "package.json");
    if (!existsSync(pkgJsonPath)) continue;
    const pkg = JSON.parse(readFileSync(pkgJsonPath, "utf8"));
    let text = "";
    for (const candidate of LICENSE_FILENAMES) {
      const p = join(dir, candidate);
      if (existsSync(p)) {
        text = readFileSync(p, "utf8").trim();
        break;
      }
    }
    packages.set(dir, {
      name: String(pkg.name ?? dir.slice(NODE_MODULES.length + 1)),
      version: String(pkg.version ?? "unknown"),
      license: typeof pkg.license === "string" ? pkg.license : JSON.stringify(pkg.license ?? "unknown"),
      text,
    });
  }
}

const sorted = [...packages.values()].sort((a, b) => a.name.localeCompare(b.name));
const lines = [
  "Third-party packages bundled into app.js and app.css.",
  "Generated by web/build.mjs; do not edit by hand.",
  "",
];
for (const p of sorted) {
  lines.push(SEPARATOR, `${p.name}@${p.version} (${p.license})`, SEPARATOR, "");
  lines.push(p.text === "" ? "(no LICENSE file in package; see package.json \"license\" field)" : p.text, "");
}
if (existsSync(LEGAL_COMMENTS_OUT)) {
  lines.push(SEPARATOR, "License comments preserved from bundled sources (esbuild legalComments)", SEPARATOR, "");
  lines.push(readFileSync(LEGAL_COMMENTS_OUT, "utf8").trim(), "");
  unlinkSync(LEGAL_COMMENTS_OUT);
}
writeFileSync(LICENSES_OUT, lines.join("\n"));
console.log(`wrote ${LICENSES_OUT} (${sorted.length} packages)`);
